const escapeHTML = value => value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const translatedText = key => escapeHTML(hebrewCopy[key]).replace(/\n/g, '<br>');
const isHebrewPath = path => /^\/he(?:\/|$)/.test(path);

/** Replace only the element's own copy, retaining its decorative icons. */
function translateContent(content, key) {
  let depth = 0, inserted = false;
  const translated = translatedText(key);
  const result = content.replace(/<[^>]+>|[^<]+/g, token => {
    if (token.startsWith('<')) {
      if (/^<br\b/i.test(token) && depth === 0) return '';
      if (/^<\//.test(token)) depth -= 1;
      else if (!/^<(?:area|base|br|col|embed|hr|img|input|link|meta|param|source|track|wbr)\b/i.test(token) && !/\/>$/.test(token)) depth += 1;
      return token;
    }
    if (depth > 0) return token;
    if (!token.trim()) return token;
    if (inserted) return '';
    inserted = true;
    return translated;
  });
  return inserted ? result : result + translated;
}

function localeLink(href, locale) {
  if (!href.startsWith('/') || href.startsWith('//')) return href;
  if (!/^\/(?:en|he)(?:\/|$)/.test(href) && !/^\/(?:$|[?#]|(?:use-cases|careers|terms|services|resources|compare)(?:\/|[?#]|$))/.test(href)) return href;
  const path = href.replace(/^\/(?:en|he)(?=\/|$)/, '') || '/';
  return locale === 'he' ? `/he${path === '/' ? '' : path}` : path;
}

/** Vite emits a real Hebrew document: translated content is present before JS. */
export function renderLocalizedHome(html, locale = 'en') {
  const hebrew = locale === 'he';
  let output = html.replace(/<html\b[^>]*>/, tag => tag
    .replace(/\blang="[^"]*"/, `lang="${locale}"`)
    .replace(/\bdir="[^"]*"/, `dir="${hebrew ? 'rtl' : 'ltr'}"`)
    .replace(/\sdata-localized="[^"]*"/g, '')
    .replace(/>$/, ` data-localized="${locale}">`));
  if (hebrew) {
    output = output.replace(/<([\w-]+)\b([^>]*\bdata-i18n="([^"]+)"[^>]*)>([\s\S]*?)<\/\1>/g,
      (match, tag, attributes, key, content) => Object.hasOwn(hebrewCopy, key)
        ? `<${tag}${attributes}>${translateContent(content, key)}</${tag}>` : match);
    for (const name of attributeNames) {
      output = output.replace(new RegExp(`<[^>]+\\bdata-i18n-${name}="([^"]+)"[^>]*>`, 'g'), (tag, key) =>
        Object.hasOwn(hebrewCopy, key) ? tag.replace(new RegExp(`(\\s${name}=")[^"]*"`), `$1${escapeHTML(hebrewCopy[key])}"`) : tag);
    }
    output = output.replace('</head>', '    <link rel="preload" href="/rubik-hebrew.woff2" as="font" type="font/woff2" crossorigin>\n  </head>');
  }
  output = output.replace(/<a\b[^>]*>/g, tag => tag.includes('data-language-switch') ? tag
    .replace(/href="[^"]*"/, `href="${hebrew ? '/' : '/he'}"`)
    .replace(/hreflang="[^"]*"/, `hreflang="${hebrew ? 'en' : 'he'}"`)
    .replace(/\slang="[^"]*"/, ` lang="${hebrew ? 'en' : 'he'}"`)
    .replace(/aria-label="[^"]*"/, `aria-label="${hebrew ? 'Switch to English' : 'Switch to Hebrew'}"`)
    : tag.replace(/href="([^"]*)"/, (_, href) => `href="${localeLink(href, locale)}"`));
  if (hebrew) output = output.replace(/(<a\b[^>]*data-language-switch[^>]*>)[^<]*(<\/a>)/g, '$1English$2');
  return output;
}

export function initializeLocalization() {
  const root = document.documentElement;
  const locale = isHebrewPath(location.pathname) ? 'he' : 'en';
  const hebrew = locale === 'he';
  root.lang = locale;
  root.dir = hebrew ? 'rtl' : 'ltr';
  // Built and development Hebrew pages are already translated. This fallback
  // also supports static servers that send index.html for every route.
  if (hebrew && root.dataset.localized !== 'he') {
    for (const node of document.querySelectorAll('[data-i18n]')) {
      if (Object.hasOwn(hebrewCopy, node.dataset.i18n)) node.innerHTML = translateContent(node.innerHTML, node.dataset.i18n);
    }
    for (const name of attributeNames) {
      for (const node of document.querySelectorAll(`[data-i18n-${name}]`)) {
        const key = node.getAttribute(`data-i18n-${name}`);
        if (Object.hasOwn(hebrewCopy, key)) node.setAttribute(name, hebrewCopy[key]);
      }
    }
  }
  root.dataset.localized = locale;
  for (const link of document.querySelectorAll('a[href]')) {
    if (link.hasAttribute('data-language-switch')) continue;
    const href = link.getAttribute('href');
    const localized = localeLink(href, locale);
    if (localized !== href) link.setAttribute('href', localized);
  }
  for (const link of document.querySelectorAll('[data-language-switch]')) {
    link.textContent = hebrew ? 'English' : 'עברית';
    link.lang = hebrew ? 'en' : 'he';
    link.hreflang = link.lang;
    link.setAttribute('aria-label', hebrew ? 'Switch to English' : 'Switch to Hebrew');
    const target = hebrew ? '/' : '/he';
    const updateDestination = () => link.setAttribute('href', `${target}${location.search}${location.hash}`);
    updateDestination();
    // The journey updates its hash with replaceState; capture the latest
    // checkpoint at activation, including keyboard and auxiliary clicks.
    link.addEventListener('click', updateDestination);
    link.addEventListener('auxclick', updateDestination);
    link.addEventListener('pointerdown', updateDestination);
  }
  return {
    locale,
    chapterNames: hebrew ? chapterKeys.map(key => hebrewCopy[`chapters.${key}`]) : englishChapters,
    motionLabels: hebrew ? { pause: hebrewCopy['motion.pause'], resume: hebrewCopy['motion.resume'] }
      : { pause: 'Pause motion', resume: 'Resume motion' },
  };
}
